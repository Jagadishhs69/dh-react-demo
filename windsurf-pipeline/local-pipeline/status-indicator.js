#!/usr/bin/env node

/**
 * Visual Status Indicator for VS Code/Windsurf
 * Creates a status file that can be monitored by the IDE
 */

const fs = require('fs');
const path = require('path');

class StatusIndicator {
    constructor(projectRoot) {
        this.projectRoot = projectRoot || process.cwd();
        this.statusFile = path.join(this.projectRoot, '.pipeline-status');
        this.statusBarFile = path.join(this.projectRoot, '.vscode', 'pipeline-status.json');
    }

    updateStatus(status, message = '', details = {}) {
        const timestamp = new Date().toISOString();
        
        // Create status indicator file
        const statusContent = {
            status: status, // 'running', 'success', 'failed', 'idle'
            message: message,
            timestamp: timestamp,
            details: details,
            icon: this.getStatusIcon(status),
            color: this.getStatusColor(status)
        };

        try {
            // Write main status file
            fs.writeFileSync(this.statusFile, JSON.stringify(statusContent, null, 2));
            
            // Write VS Code status bar file
            fs.writeFileSync(this.statusBarFile, JSON.stringify({
                text: `$(${statusContent.icon}) ${message}`,
                color: statusContent.color,
                tooltip: `Pipeline Status: ${status}\nLast Updated: ${timestamp}`,
                command: "workbench.action.terminal.focus"
            }, null, 2));

            // Create visual indicator in project root
            this.createVisualIndicator(status, message);
            
        } catch (error) {
            console.error('Failed to update status indicator:', error.message);
        }
    }

    getStatusIcon(status) {
        const icons = {
            'running': 'sync~spin',
            'success': 'check',
            'failed': 'error',
            'idle': 'circle-outline'
        };
        return icons[status] || 'circle-outline';
    }

    getStatusColor(status) {
        const colors = {
            'running': '#FFA500', // Orange
            'success': '#00FF00', // Green
            'failed': '#FF0000',  // Red
            'idle': '#808080'     // Gray
        };
        return colors[status] || '#808080';
    }

    createVisualIndicator(status, message) {
        const indicators = {
            'running': '🔄 PIPELINE RUNNING',
            'success': '✅ PIPELINE SUCCESS',
            'failed': '❌ PIPELINE FAILED',
            'idle': '⚪ PIPELINE IDLE'
        };

        const indicatorFile = path.join(this.projectRoot, 'PIPELINE_STATUS.md');
        const content = `# ${indicators[status] || '⚪ PIPELINE STATUS'}

**Status**: ${status.toUpperCase()}  
**Message**: ${message}  
**Last Updated**: ${new Date().toLocaleString()}  

---
*This file is auto-generated by the Windsurf Local CI/CD Pipeline*
`;

        fs.writeFileSync(indicatorFile, content);
    }

    clearStatus() {
        try {
            if (fs.existsSync(this.statusFile)) {
                fs.unlinkSync(this.statusFile);
            }
            if (fs.existsSync(this.statusBarFile)) {
                fs.unlinkSync(this.statusBarFile);
            }
            
            const indicatorFile = path.join(this.projectRoot, 'PIPELINE_STATUS.md');
            if (fs.existsSync(indicatorFile)) {
                fs.unlinkSync(indicatorFile);
            }
        } catch (error) {
            // Ignore cleanup errors
        }
    }
}

module.exports = StatusIndicator;
